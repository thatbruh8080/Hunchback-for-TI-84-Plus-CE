/* Install once after gfx_Begin(), with the default GraphX font active. */
static inline void hunchInstallFont(void)
{
    gfx_SetCharData(' ', hunchGlyphs[0]);
    for (unsigned i = 0; i < 26; ++i)
        gfx_SetCharData('A' + i, hunchGlyphs[1 + i]);
    for (unsigned i = 0; i < 10; ++i)
        gfx_SetCharData('0' + i, hunchGlyphs[27 + i]);
    gfx_SetCharData('.', hunchGlyphs[37]);
    static const uint8_t exclamation[8] = {0x18, 0x18, 0x18, 0x18, 0x18, 0, 0x18, 0};
    gfx_SetCharData('!', exclamation);
    static const uint8_t colon[8] = {0, 0x18, 0x18, 0, 0, 0x18, 0x18, 0};
    gfx_SetCharData(':', colon);
    // Infinity from the developer-menu mockup. Eight bytes, endless bad jumps.
    static const uint8_t infinity[8] = {0, 0, 0x66, 0x99, 0x99, 0x66, 0, 0};
    gfx_SetCharData(0x80, infinity);
    for (unsigned i = 0; i < 26; ++i)
        gfx_SetCharData('a' + i, hunchLowercase[i]);
    gfx_SetMonospaceFont(8);
}

